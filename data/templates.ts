export const createProjectFromTemplate = (template: StarterTemplate): Project => {
  const timestamp = Date.now();
  const rawLayers = template.state.artboards?.[0]?.layers || (template.state as any).layers || [];
  const canvasWidth = template.size.width;
  const canvasHeight = template.size.height;

  return {
    id: `tmpl_${template.id}_${timestamp}`,
    name: template.name,
    updatedAt: timestamp,
    state: {
      ...template.state,
      canvasSize: template.size,
      canvasBackgroundColor: template.state.canvasBackgroundColor || '#0f172a',
      activeArtboardId: 'default-artboard',
      artboards: [
        {
          id: 'default-artboard',
          name: 'Artboard 1',
          x: 0,
          y: 0,
          width: canvasWidth,
          height: canvasHeight,
          layers: rawLayers,
        },
      ],
    } as unknown as Project['state'],
  };
};
