export const createProjectFromTemplate = (template: StarterTemplate): Project => {
  const timestamp = Date.now();
  return {
    id: `tmpl_${template.id}_${timestamp}`,
    name: template.name,
    updatedAt: timestamp,
    state: template.state
  };
};

